#!/usr/bin/env python3
"""Lists the TV's installed apps via SSAP and saves their icons.

    python3 tools/list_apps.py [ip]
    python3 tools/list_apps.py --pair-helper     # once: pairs the helper (Home takeover, screen off)

Writes tools/apps.local.json (every launch point) and app/icons/<id>.png for each icon the TV serves.
Pick the ones you want and put them in app/config.js.
"""
import json
import os
import re
import ssl
import sys
import urllib.parse
import urllib.request

from tvlib import default_ip, ssap

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS = os.path.join(ROOT, 'app', 'icons')


def fetch_icon(ip, url, app_id):
    parts = urllib.parse.urlsplit(url or '')
    ext = os.path.splitext(parts.path)[1].lower()
    if parts.scheme not in ('http', 'https') or parts.hostname != ip or ext not in ('.png', '.jpg', '.jpeg', '.webp'):
        return ''
    try:
        ctx = ssl._create_unverified_context()   # the TV's self-signed certificate
        with urllib.request.urlopen(url, timeout=10, context=ctx) as r:
            data = r.read()
    except OSError:
        return ''
    name = re.sub(r'[^\w.-]', '_', app_id) + ext
    with open(os.path.join(ICONS, name), 'wb') as f:
        f.write(data)
    return 'icons/' + name


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    ip = args[0] if args else default_ip()
    if '--pair-helper' in sys.argv:
        # Pairs the on-TV helper's SSAP client (tools/ssap_manifest.json); the TV asks once to allow it.
        print(ssap(ip, 'com.webos.service.tvpower/power/getPowerState', home=True))
        return
    points = ssap(ip, 'com.webos.applicationManager/listLaunchPoints').get('launchPoints') or []
    os.makedirs(ICONS, exist_ok=True)
    apps = []
    for p in points:
        if not p.get('id'):
            continue
        apps.append({'id': p['id'], 'title': p.get('title') or p['id'],
                     'icon': fetch_icon(ip, p.get('largeIcon') or p.get('icon'), p['id']),
                     'color': p.get('bgColor') or p.get('iconColor') or ''})
    with open(os.path.join(ROOT, 'tools', 'apps.local.json'), 'w', encoding='utf-8') as f:
        json.dump(apps, f, ensure_ascii=False, indent=1)
    # The All apps drawer: everything except inputs (they're in the Inputs picker) and this launcher.
    drawer = [{'id': a['id'], 'title': a['title'], 'icon': a['icon']} for a in apps
              if not re.match(r'^com\.webos\.app\.(hdmi\d|livetv)$', a['id']) and a['id'] != 'io.tvlauncher.home']
    with open(os.path.join(ROOT, 'app', 'apps.js'), 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/list_apps.py: every app on the TV, for the All apps drawer. */\n')
        f.write('window.ALL_APPS = ' + json.dumps(drawer, ensure_ascii=False, indent=1) + ';\n')
    for i, a in enumerate(apps, 1):
        print('%2d. %-28s %s' % (i, a['title'], a['id']))


if __name__ == '__main__':
    main()
